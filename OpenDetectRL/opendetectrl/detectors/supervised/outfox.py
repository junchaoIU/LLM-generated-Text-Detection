"""OUTFOX: LLM-Generated Essay Detection Through In-Context Learning.

Paper: Koike et al., "OUTFOX: LLM-Generated Essay Detection Through
In-Context Learning with Adversarially Generated Examples", AAAI 2024.
Repo: https://github.com/ryuryukke/OUTFOX

OUTFOX uses in-context learning: a few-shot prompt with human/AI essay
examples is fed to an LLM, which then classifies the target text.  The
detection score is the log-probability ratio of the "AI" label vs the
"human" label.

This implementation supports any HuggingFace causal LM (default: GPT-2)
or an OpenAI chat model.
"""
import os
from typing import List, Optional

import numpy as np

from ...core.base import BaseDetector
from ...core.registry import register_detector

_DEFAULT_FEW_SHOT = [
    ("Students should wear school uniforms because they promote equality "
     "and reduce bullying. When everyone dresses the same, there is less "
     "pressure to wear expensive brands.",
     "human"),
    ("In today's rapidly evolving educational landscape, the implementation "
     "of standardized dress codes serves as a cornerstone for fostering "
     "an environment conducive to academic excellence and social cohesion.",
     "ai"),
]

_PROMPT_TEMPLATE = (
    "Determine if the following text is written by a human or generated by AI.\n\n"
    "Text: {text}\n"
    "Label: {label}\n\n"
)


@register_detector("outfox")
class OUTFOXDetector(BaseDetector):
    """OUTFOX detector using in-context learning.

    Constructs a few-shot prompt with human/AI examples, then asks the LM
    to classify the target text.  Score = P("ai") / (P("ai") + P("human"))
    based on the log-probability of the label tokens.
    """

    DEFAULT_MODEL_NAME = "gpt2"

    def __init__(
        self,
        model_name: str = None,
        examples: Optional[List] = None,
        max_length: int = 1024,
        threshold: float = 0.5,
        device: Optional[str] = None,
        use_openai: bool = False,
        openai_model: str = "gpt-4o-mini",
        openai_api_key: Optional[str] = None,
        **kwargs,
    ):
        super().__init__(threshold=threshold, device=device, **kwargs)
        self.model_name = model_name or self.DEFAULT_MODEL_NAME
        self.max_length = max_length
        self.use_openai = use_openai
        self.openai_model = openai_model
        self.openai_api_key = openai_api_key or os.environ.get("OPENAI_API_KEY")
        self.examples = examples or _DEFAULT_FEW_SHOT

        if not use_openai:
            import torch
            import transformers

            if device is None:
                device = "cuda" if torch.cuda.is_available() else "cpu"
            self.device = torch.device(device)
            self.tokenizer = transformers.AutoTokenizer.from_pretrained(
                self.model_name
            )
            if self.tokenizer.pad_token is None:
                self.tokenizer.pad_token = self.tokenizer.eos_token
            self.model = transformers.AutoModelForCausalLM.from_pretrained(
                self.model_name
            ).to(self.device)
            self.model.eval()
            self._torch = torch

    def _build_prompt(self, target_text: str) -> str:
        """Build the few-shot prompt ending with the target text."""
        parts = []
        for text, label in self.examples:
            parts.append(_PROMPT_TEMPLATE.format(text=text[:200], label=label))
        parts.append(
            _PROMPT_TEMPLATE.format(text=target_text, label="").rstrip()
        )
        return "".join(parts)

    @staticmethod
    def _token_logprob(model, tokenizer, prompt_ids, target_ids, device):
        """Compute the sum log-probability of ``target_ids`` given context."""
        import torch
        import torch.nn.functional as F

        full_ids = torch.cat([prompt_ids, target_ids], dim=1).to(device)
        with torch.inference_mode():
            logits = model(full_ids).logits

        # Predict target_ids tokens: logits at positions [len(prompt)-1 .. len(prompt)+len(target)-2]
        start = prompt_ids.shape[1] - 1
        end = start + target_ids.shape[1]
        log_probs = F.log_softmax(logits[0, start:end, :], dim=-1)
        token_log_probs = log_probs.gather(
            1, target_ids[0].to(device).unsqueeze(1)
        ).squeeze(1)
        return token_log_probs.sum().item()

    def _score_hf(self, text: str) -> float:
        """Score using a HuggingFace causal LM."""
        torch = self._torch
        prompt = self._build_prompt(text)
        prompt_ids = self.tokenizer.encode(
            prompt, return_tensors="pt", truncation=True, max_length=self.max_length
        )

        scores = {}
        for label in ("human", "ai"):
            label_ids = self.tokenizer.encode(
                label, return_tensors="pt", add_special_tokens=False
            )
            lp = self._token_logprob(
                self.model, self.tokenizer, prompt_ids, label_ids, self.device
            )
            scores[label] = lp

        # Softmax over the two labels
        max_lp = max(scores.values())
        exp_scores = {k: np.exp(v - max_lp) for k, v in scores.items()}
        total = sum(exp_scores.values())
        return exp_scores["ai"] / total  # higher = more AI

    def _score_openai(self, text: str) -> float:
        """Score using OpenAI chat API."""
        from openai import OpenAI

        client = OpenAI(api_key=self.openai_api_key)
        prompt = self._build_prompt(text)
        response = client.chat.completions.create(
            model=self.openai_model,
            messages=[{"role": "user", "content": prompt}],
            max_tokens=5,
            temperature=0.0,
        )
        answer = response.choices[0].message.content.strip().lower()
        return 1.0 if "ai" in answer else 0.0

    def score(self, texts) -> np.ndarray:
        texts = list(texts)
        scores = []
        for text in texts:
            if self.use_openai:
                scores.append(self._score_openai(text))
            else:
                scores.append(self._score_hf(text))
        return np.asarray(scores, dtype=float)
