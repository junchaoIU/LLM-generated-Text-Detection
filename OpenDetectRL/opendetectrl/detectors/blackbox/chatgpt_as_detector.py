"""ChatGPT-as-Detector: prompting ChatGPT to judge AI vs human text.

Paper: Bhattacharjee & Liu, "Fighting Fire with Fire: Can ChatGPT Detect
AI-Generated Text?", SIGKDD Explorations 2023.
Repo: https://github.com/amritabh/chatgpt-as-detector

Method: the text is submitted to ChatGPT along with a prompt asking it to
classify the text as written by a human or by an AI, and to return a
confidence score.  The detector score is the probability mass assigned to
the "ai" label relative to the "human" label.

This implementation supports any HuggingFace causal LM (default: GPT-2)
as a local proxy, or an OpenAI chat model.
"""
import os
from typing import Optional

import numpy as np

from ...core.base import BaseDetector
from ...core.registry import register_detector

_DEFAULT_PROMPT_TEMPLATE = (
    "I need to decide whether the following text was written by a human or "
    "generated by an AI model. Please output your verdict as either "
    "\"ai\" or \"human\", followed by a confidence score between 0 and 1.\n\n"
    "Text: {text}\n"
    "Verdict: "
)


@register_detector("chatgpt_as_detector")
class ChatGPTAsDetectorDetector(BaseDetector):
    """ChatGPT-as-detector: prompt an LLM to label a text human/AI.

    A single prompt is built from the target text and fed to a black-box
    LLM.  For the HuggingFace path the log-probability of the "ai" and
    "human" label tokens is computed and the score is
    ``P("ai") / (P("ai") + P("human"))`` (higher = more AI).  For the
    OpenAI path the model is asked to return a verdict and a confidence
    score which is used directly.
    """

    DEFAULT_MODEL_NAME = "gpt2"

    def __init__(
        self,
        model_name: str = "gpt2",
        use_openai: bool = False,
        openai_model: str = "gpt-4o-mini",
        openai_api_key: Optional[str] = None,
        prompt_template: Optional[str] = None,
        threshold: float = 0.5,
        device: Optional[str] = None,
        **kwargs,
    ):
        super().__init__(threshold=threshold, device=device, **kwargs)
        self.model_name = model_name
        self.use_openai = use_openai
        self.openai_model = openai_model
        self.openai_api_key = openai_api_key or os.environ.get("OPENAI_API_KEY")
        self.prompt_template = prompt_template or _DEFAULT_PROMPT_TEMPLATE

        if not use_openai:
            import torch
            import transformers

            if device is None:
                device = "cuda" if torch.cuda.is_available() else "cpu"
            self.device = torch.device(device)
            self.tokenizer = transformers.AutoTokenizer.from_pretrained(
                self.model_name
            )
            if self.tokenizer.pad_token is None:
                self.tokenizer.pad_token = self.tokenizer.eos_token
            self.model = transformers.AutoModelForCausalLM.from_pretrained(
                self.model_name
            ).to(self.device)
            self.model.eval()
            self._torch = torch

    def _build_prompt(self, target_text: str) -> str:
        """Build the single-prompt classification prompt."""
        return self.prompt_template.format(text=target_text)

    @staticmethod
    def _token_logprob(model, tokenizer, prompt_ids, target_ids, device):
        """Compute the sum log-probability of ``target_ids`` given context."""
        import torch
        import torch.nn.functional as F

        full_ids = torch.cat([prompt_ids, target_ids], dim=1).to(device)
        with torch.inference_mode():
            logits = model(full_ids).logits

        start = prompt_ids.shape[1] - 1
        end = start + target_ids.shape[1]
        log_probs = F.log_softmax(logits[0, start:end, :], dim=-1)
        token_log_probs = log_probs.gather(
            1, target_ids[0].to(device).unsqueeze(1)
        ).squeeze(1)
        return token_log_probs.sum().item()

    def _score_hf(self, text: str) -> float:
        """Score using a HuggingFace causal LM."""
        prompt = self._build_prompt(text)
        prompt_ids = self.tokenizer.encode(
            prompt, return_tensors="pt", truncation=True, max_length=1024
        )

        scores = {}
        for label in ("human", "ai"):
            label_ids = self.tokenizer.encode(
                label, return_tensors="pt", add_special_tokens=False
            )
            lp = self._token_logprob(
                self.model, self.tokenizer, prompt_ids, label_ids, self.device
            )
            scores[label] = lp

        max_lp = max(scores.values())
        exp_scores = {k: np.exp(v - max_lp) for k, v in scores.items()}
        total = sum(exp_scores.values())
        return exp_scores["ai"] / total  # higher = more AI

    def _score_openai(self, text: str) -> float:
        """Score using OpenAI chat API."""
        from openai import OpenAI

        client = OpenAI(api_key=self.openai_api_key)
        prompt = self._build_prompt(text)
        response = client.chat.completions.create(
            model=self.openai_model,
            messages=[{"role": "user", "content": prompt}],
            max_tokens=20,
            temperature=0.0,
        )
        answer = response.choices[0].message.content.strip().lower()

        # Try to extract a numeric confidence score like "0.8" from the answer.
        score = self._parse_confidence(answer)
        if score is None:
            # Fall back to a verdict-only heuristic.
            return 1.0 if "ai" in answer else 0.0
        return score

    @staticmethod
    def _parse_confidence(answer: str) -> Optional[float]:
        """Best-effort parse of a confidence score from an LLM answer."""
        import re

        match = re.search(r"(\d(?:\.\d+)?)", answer)
        if match:
            try:
                value = float(match.group(1))
            except ValueError:
                return None
            if 0.0 <= value <= 1.0:
                return value
        return None

    def score(self, texts) -> np.ndarray:
        texts = list(texts)
        scores = []
        for text in texts:
            if self.use_openai:
                scores.append(self._score_openai(text))
            else:
                scores.append(self._score_hf(text))
        return np.asarray(scores, dtype=float)